from pathlib import Path
from tempfile import NamedTemporaryFile, mkdtemp
import base64
import hashlib
import os
import shutil

def install():
    root = Path('/var/www/azmednsk-preview')
    page = root / 'team/index.html'
    prefix = '/assets/team2-v1/dental-cherevko-'
    old = prefix + '71b601f5.webp'
    new = prefix + 'f508a6df.webp'
    html = page.read_bytes()
    data = base64.b64decode(PHOTO)
    digest = hashlib.sha256(data).hexdigest()
    assert digest == 'f508a6dfb66cf5f9b1d9b8858b669c5d33ab3a4a4e48c2f4cab768064011f92b'
    target = root / new[1:]
    if target.exists() and target.read_bytes() != data:
        raise SystemExit('STOP: existing portrait differs')
    def image_tag(path):
        return ('src="' + path + '" alt="Черевко Анна Сергеевна"').encode()
    if html.count(image_tag(new)) == 1 and target.is_file():
        print('PORTRAIT=ALREADY_INSTALLED')
        return
    if html.count(image_tag(old)) != 1 or not (root / old[1:]).is_file():
        raise SystemExit('STOP: team card changed')
    backup = Path(mkdtemp(prefix='cherevko-', dir='/var/backups/azmednsk'))
    shutil.copy2(page, backup / 'index.html')
    print('BACKUP=', backup, sep='')
    if not target.exists():
        with NamedTemporaryFile(dir=target.parent, delete=False) as tmp:
            tmp.write(data)
        os.chmod(tmp.name, 0o644)
        os.replace(tmp.name, target)
    with NamedTemporaryFile(dir=page.parent, delete=False) as tmp:
        tmp.write(html.replace(image_tag(old), image_tag(new)))
    shutil.copymode(page, tmp.name)
    if page.read_bytes() != html:
        os.unlink(tmp.name)
        raise SystemExit('STOP: page changed')
    os.replace(tmp.name, page)
    print('PORTRAIT=PASS')

